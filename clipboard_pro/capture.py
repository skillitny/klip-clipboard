"""Capture native du presse-papiers macOS via NSPasteboard.

On surveille `changeCount` (incrémenté à chaque modification système) plutôt que
de spawner `pbpaste` en boucle : c'est instantané et ~zéro CPU.

Les types « concealed » et « transient » publiés par les gestionnaires de mots
de passe (1Password, Bitwarden, Apple Keychain, …) sont automatiquement ignorés.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Optional

from AppKit import (  # type: ignore[import]
    NSPasteboard,
    NSPasteboardTypePNG,
    NSPasteboardTypeString,
    NSPasteboardTypeTIFF,
    NSBitmapImageRep,
    NSWorkspace,
)

# Types officieux mais largement respectés par les gestionnaires de secrets.
SECRET_TYPES = {
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "com.agilebits.onepassword4",
    "Pasteboard generator type",
}


@dataclass
class CapturedText:
    text: str
    source_app: Optional[str]


@dataclass
class CapturedImage:
    png: bytes
    width: int
    height: int
    source_app: Optional[str]


class ClipboardWatcher:
    """À appeler périodiquement (timer Qt) ; renvoie un payload si nouveauté."""

    def __init__(self) -> None:
        self._pb = NSPasteboard.generalPasteboard()
        self._last_change = self._pb.changeCount()

    @staticmethod
    def _front_app() -> Optional[str]:
        try:
            app = NSWorkspace.sharedWorkspace().frontmostApplication()
            return app.localizedName() if app else None
        except Exception:
            return None

    @staticmethod
    def _is_secret(types) -> bool:
        if not types:
            return False
        for t in types:
            if str(t) in SECRET_TYPES:
                return True
        return False

    def poll(self):
        """Renvoie CapturedText | CapturedImage | None."""
        change = self._pb.changeCount()
        if change == self._last_change:
            return None
        self._last_change = change

        types = list(self._pb.types() or [])
        if self._is_secret(types):
            return None

        # Image en priorité (souvent un copier-coller d'image embarque aussi du
        # texte de fallback "Image")
        if NSPasteboardTypePNG in types:
            data = self._pb.dataForType_(NSPasteboardTypePNG)
            if data:
                blob = bytes(data)
                rep = NSBitmapImageRep.imageRepWithData_(data)
                w = int(rep.pixelsWide()) if rep else 0
                h = int(rep.pixelsHigh()) if rep else 0
                return CapturedImage(blob, w, h, self._front_app())

        if NSPasteboardTypeTIFF in types:
            data = self._pb.dataForType_(NSPasteboardTypeTIFF)
            if data:
                rep = NSBitmapImageRep.imageRepWithData_(data)
                if rep is not None:
                    png = rep.representationUsingType_properties_(4, None)  # NSPNGFileType=4
                    if png:
                        return CapturedImage(
                            bytes(png),
                            int(rep.pixelsWide()),
                            int(rep.pixelsHigh()),
                            self._front_app(),
                        )

        if NSPasteboardTypeString in types:
            text = self._pb.stringForType_(NSPasteboardTypeString)
            if text:
                return CapturedText(str(text), self._front_app())

        return None


def write_text(text: str) -> None:
    pb = NSPasteboard.generalPasteboard()
    pb.clearContents()
    pb.setString_forType_(text, NSPasteboardTypeString)


def write_image(blob: bytes) -> None:
    from Foundation import NSData  # type: ignore[import]
    pb = NSPasteboard.generalPasteboard()
    pb.clearContents()
    data = NSData.dataWithBytes_length_(blob, len(blob))
    pb.setData_forType_(data, NSPasteboardTypePNG)


def png_dimensions(blob: bytes) -> tuple[int, int]:
    """Retourne (width, height) en pixels à partir des bytes PNG.

    Utilise NSBitmapImageRep pour rester cohérent avec le reste du code de
    capture. Renvoie (0, 0) si le blob n'est pas décodable.
    """
    from Foundation import NSData  # type: ignore[import]
    try:
        data = NSData.dataWithBytes_length_(blob, len(blob))
        rep = NSBitmapImageRep.imageRepWithData_(data)
        if rep is not None:
            return int(rep.pixelsWide()), int(rep.pixelsHigh())
    except Exception:
        pass
    return 0, 0
